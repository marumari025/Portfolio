/* =====================================================================
   content.js ― 文章と設定は、すべてこのファイルに書きます
   index.html（見た目と仕組み）は、普段は触らなくて大丈夫です。

   【書き方のルール】
   ・文字は "ダブルクォーテーション" で囲む
   ・{ … } や [ … ] の「1つのまとまり」の間は、「,（カンマ）」で区切る
     （増やすときは、まとまりをコピーして貼り、前のまとまりの後ろに , を付ける）
   ・減らすときは、まとまりをまとめて消す
   ・うまく表示されなくなったら、カンマ , と引用符 " の付け忘れを探す
   ・// から後ろ（行の終わりまで）は、メモ書きです。動作には関係ありません

   【文章の中で使える書き方】（文章を書く場所で共通）
   ・**ここ**   → 太字になる
   ・改行       → ` ` （バッククォート）の中で Enter を押した位置が、そのまま画面でも改行になります
                  （"…" で囲む文字列の中では、\n と書くと改行になります）
                  改行しなかった所は、画面の幅に合わせて自動で折り返されます
   ・字下げ     → 行の最初の空白は、画面では無視されます。そろえて書いて大丈夫です
   ・空行       → 段落が分かれる（作品の説明などでは、段落の間があきます）
   ・<br>       → 使えません（書くと、その文字が、そのまま画面に出ます）
   ・文の途中で改行すると、画面でも、その位置で切れます。続けて書きたいときは、改行しません

   【目次】（ページに出る順番と、同じ並びです）
     1. ページ全体の設定         … タブの名前、ナビ（項目名と並び順）
     2. トップ・フッター         … 名前、肩書き
     3. 自己紹介                 … 文章と画像
     4. 自作エンジン
     5. 自作エンジンで作った作品 … 開きっぱなしで見せる、大きな作品紹介
     6. その他の作品             … 横にスライドするカード
     7. 使用スキル
     8. 資格
     9. 連絡先
    10. 今は表示していない項目   … 特技・趣味、自己PR

   【使わない項目について】
   ・ナビ（nav_text）に書かない項目は、ページに出ません
   ・中身が空（[] など）の項目も、自動で隠れます
   ・この下の変数（const …）を、まとめて消しても、サイトは止まりません
   ===================================================================== */

